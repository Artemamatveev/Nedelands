// Writes api/_scenes.js: the everyday situations of the AI conversations, made from the scripted conversations in
// GP (data/extra.js, the ONA ones left out). The server gives Claude the script as a model conversation, so the facts in
// it (prices, times, rules, names) stay the checked ones. Run after changing GP: `node tools/build-scenes.mjs`
// (tests/talk.test.mjs fails when the file is out of date). `v` in GP is the person's voice: F or M.
import fs from "node:fs";
import vm from "node:vm";

const root = new URL("../", import.meta.url);
export function scenes() {
  const ctx = vm.createContext({ window: {} });
  vm.runInContext(fs.readFileSync(new URL("data/extra.js", root), "utf8") + ";globalThis.GP=GP", ctx);
  const plain = (t) => String(t).replace(/\[([^\]]*)\]/g, "$1").trim();
  const out = {};
  for (const c of ctx.GP) {
    if (c.ona) continue;
    out[c.id] = {
      who: c.w, g: c.v === "M" ? "M" : "F", formal: c.d.some((s) => /\b(u|uw)\b/.test(s.a)) ? 1 : 0,
      title: c.t, task: c.o, open: c.d[0].a, ...(c.b1 ? { b1: 1 } : {}),
      model: c.d.map((s) => [s.a, plain(s.m)]), end: c.e,
    };
  }
  return out;
}
export const source = () => `// Generated by tools/build-scenes.mjs from GP in data/extra.js: don't edit by hand.\nexport const SCENES = ${JSON.stringify(scenes(), null, 1)};\n`;
if (import.meta.url === `file://${process.argv[1]}`) {
  fs.writeFileSync(new URL("api/_scenes.js", root), source());
  console.log("api/_scenes.js:", Object.keys(scenes()).length, "scenes");
}
