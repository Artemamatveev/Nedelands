"""Build local SVG brush lettering; no runtime font or image request.
Usage: python tools/build-praise.py /path/to/PermanentMarker-Regular.ttf
Font Diner, Apache 2.0; source and license: art/praise-LICENSE.txt.
"""
import json
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

root = Path(__file__).resolve().parents[1]
font = TTFont(sys.argv[1])
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
phrases = [('Goed zo!', ['GOED ZO!']), ('Lekker bezig!', ['LEKKER', 'BEZIG!']),
           ('Helemaal goed!', ['HELEMAAL', 'GOED!']), ('Top!', ['TOP!']),
           ('Netjes!', ['NETJES!']), ('Mooi zo!', ['MOOI ZO!'])]

def draw_line(text, top, height):
    bounds = BoundsPen(glyphs)
    cursor = 0
    for char in text:
        name = cmap[ord(char)]
        glyphs[name].draw(TransformPen(bounds, (1, 0, 0, 1, cursor, 0)))
        cursor += font['hmtx'][name][0]
    xmin, ymin, xmax, ymax = bounds.bounds
    scale = min(292 / (xmax - xmin), height / (ymax - ymin))
    tx = (360 - (xmax - xmin) * scale) / 2 - xmin * scale
    ty = top + ymax * scale
    pen = SVGPathPen(glyphs, ntos=lambda n: ('%.2f' % n).rstrip('0').rstrip('.') if n else '0')
    cursor = 0
    for char in text:
        name = cmap[ord(char)]
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, tx + cursor * scale, ty)))
        cursor += font['hmtx'][name][0]
    return pen.getCommands()

art = []
for text, lines in phrases:
    targets = [(47, 65)] if len(lines) == 1 else [(28, 42), (79, 43)]
    art.append({'text': text, 'path': ' '.join(draw_line(line, *target) for line, target in zip(lines, targets))})
header = '// Generated by tools/build-praise.py. Permanent Marker outlines by Font Diner, Apache 2.0.\n// Copyright (c) 2010 Font Diner, Inc. See art/praise-LICENSE.txt.\n'
(root / 'study/praise-art-v1.js').write_text(header + 'const PRAISE_ART=' + json.dumps(art, ensure_ascii=False, separators=(',', ':')) + ';\n')
